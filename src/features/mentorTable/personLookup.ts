export interface MentorImageChainOptions {
  name: string;
  /** Extra external candidates (state/hydration results); dev chain only. */
  externalCandidates?: string[];
  /** Locale-aware inline initials avatar, computed by the caller. */
  initialsAvatar: string;
  isDev: boolean;
}

/**
 * Ordered image fallback ladder for a mentor avatar.
 *
 * production CSP is `img-src 'self' data: blob:` — every external
 * image host (wikimedia, dicebear, ui-avatars, 16personalities) is blocked,
 * and CN networks block the same hosts regardless. The production chain is
 * therefore exactly two entries:
 *   1. the same-origin /api/mentor-image proxy (serves bundled local assets
 *      first, then fetches + caches from Wikipedia server-side)
 *   2. the caller's inline initials avatar (data: URI, always renders)
 *
 * DEV has no CSP and reachable hosts, so it keeps the full ladder: proxy,
 * direct worker URL (outside the dev-server proxy), external candidates,
 * dicebear cartoon, initials.
 */
export function buildMentorImageChain(options: MentorImageChainOptions): string[] {
  let resolvedName = options.name;
  let verifiedImages: string[] = [];
  try {
    const verified = findVerifiedPerson(options.name);
    if (verified) {
      resolvedName = verified.canonical;
      verifiedImages = [verified.imageUrl, ...(verified.candidateImageUrls ?? [])].filter(
        Boolean
      ) as string[];
    }
  } catch {
    /* findVerifiedPerson may be unavailable in some test harnesses */
  }

  const proxyUrl = `/api/mentor-image?name=${encodeURIComponent(resolvedName)}`;
  if (!options.isDev) {
    return [proxyUrl, options.initialsAvatar];
  }

  // Local dev fallback: the Vite dev server proxies /api/mentor-image, but
  // when running outside the dev server we hit the worker directly.
  const localFallback = `http://127.0.0.1:8787/api/mentor-image?name=${encodeURIComponent(resolvedName)}`;
  const external = Array.from(
    new Set([...(options.externalCandidates ?? []), ...verifiedImages].filter(Boolean))
  ) as string[];
  return [
    proxyUrl,
    localFallback,
    ...external,
    getCartoonAvatarUrl(resolvedName),
    options.initialsAvatar,
  ];
}

export async function fetchPersonImage(name: string): Promise<string | undefined> {
  const key = normalizeName(name);
  // key is always non-empty when name is a non-empty string; callers always
  // pass a trimmed name so we don't re-guard here.
  if (imageCache.has(key)) return imageCacheGet(key);
  if (isMbtiCode(name)) {
    const mbti = buildMbtiOption(name).imageUrl;
    imageCacheSet(key, mbti);
    return mbti;
  }

  // the client-side Wikipedia lookups below cannot work in production —
  // CSP `connect-src 'self'` blocks en.wikipedia.org outright, and it is
  // network-unreachable for the primary CN audience regardless. Production
  // hydrates from the bundled local asset when one exists and otherwise
  // leaves the image to the /api/mentor-image proxy chain at render time.
  // DEV keeps live Wikipedia hydration for local DX.
  if (!import.meta.env.DEV) {
    const local = getLocalImagePath(findVerifiedPerson(name)?.canonical ?? name);
    if (local) {
      imageCacheSet(key, local);
      return local;
    }
    return undefined;
  }

  const verified = findVerifiedPerson(name);
  if (verified?.imageUrl) {
    imageCacheSet(key, verified.imageUrl);
    return verified.imageUrl;
  }
  // Try exact Wikipedia title lookup first
  const wiki = await fetchWikiImageByTitle(name);
  if (wiki?.imageUrl) {
    imageCacheSet(key, wiki.imageUrl);
    return wiki.imageUrl;
  }
  // Fall back to Wikipedia search, then name avatar.
  // withAvatarFallback guarantees imageUrl is always defined on results.
  const searchResults = await searchWikipediaPeople(name, 1);
  const image = searchResults.length > 0 ? searchResults[0].imageUrl! : buildNameAvatar(name);
  imageCacheSet(key, image);
  return image;
}

export async function fetchPersonImageCandidates(name: string): Promise<string[] | undefined> {
  const fallback = buildNameAvatar(name);
  if (isMbtiCode(name)) {
    // buildMbtiOption always populates candidateImageUrls.
    return buildMbtiOption(name).candidateImageUrls!;
  }
  // candidate URLs feed only the dev image chain; the production chain
  // is proxy → initials and ignores them, so client-side Wikipedia candidate
  // hydration is dead weight there. See fetchPersonImage for the full rationale.
  if (!import.meta.env.DEV) return undefined;
  const verified = findVerifiedPerson(name);
  if (verified) {
    // findVerifiedPerson always sets candidateImageUrls (possibly empty array).
    const combined = [verified.imageUrl, ...verified.candidateImageUrls!, fallback].filter(Boolean);
    return Array.from(new Set(combined));
  }
  // Try exact Wikipedia title lookup first
  const wiki = await fetchWikiImageByTitle(name);
  if (wiki?.imageUrl) return Array.from(new Set([wiki.imageUrl, fallback]));
  // Fall back to Wikipedia search, then name avatar
  const searchResults = await searchWikipediaPeople(name, 3);
  const images = searchResults.map((r) => r.imageUrl).filter(Boolean) as string[];
  return images.length > 0 ? [...images, fallback] : [fallback];
}

export async function searchPeopleWithPhotos(query: string, limit = 6): Promise<PersonOption[]> {
  const q = query.trim();
  if (!q) return [];

  const normalized = normalizeName(q);
  // R2D ALGO-4: iterate the pre-normalized NORMALIZED_ENTRIES instead of
  // re-normalizing every alias on every call.
  const verifiedScored: Array<{ entry: NormalizedEntry; score: number }> = [];
  for (const entry of NORMALIZED_ENTRIES) {
    if (entry.haystack.some((text) => text.includes(normalized))) {
      verifiedScored.push({ entry, score: nameRelevanceFromHaystack(entry.haystack, normalized) });
    }
  }
  verifiedScored.sort((a, b) => a.score - b.score);
  const verifiedMatches = verifiedScored
    .slice(0, Math.max(1, Math.min(limit, 10)))
    .map(({ entry }) => withAvatarFallback({
      name: entry.person.canonical,
      imageUrl: entry.person.imageUrl,
      candidateImageUrls: entry.person.candidateImageUrls,
      description: entry.person.description,
      descriptionZh: entry.person.descriptionZh
    }));

  const mbtiMatches = MBTI_TYPES
    .filter((code) => normalizeName(code).includes(normalized))
    .map((code) => buildMbtiOption(code));

  // production search is local-data only (CSP connect-src 'self' blocks
  // the client-side Wikipedia query, and CN networks block it anyway). The
  // typed-query fallback below still gives users a usable "add custom mentor"
  // option for people outside the bundled data.
  const wikiMatches = import.meta.env.DEV ? await searchWikipediaPeople(q, limit) : [];
  const merged = [...verifiedMatches, ...mbtiMatches, ...wikiMatches];
  const unique = new Map<string, PersonOption>();
  const score = (person: PersonOption) => {
    const generated = (url: string) => url.startsWith('data:image/svg+xml') || url.includes('ui-avatars.com/api');
    // score() is only called on withAvatarFallback-wrapped persons, so
    // imageUrl is guaranteed non-generated and candidateImageUrls is an array.
    const imageScore = 6;
    const candidateScore = person.candidateImageUrls!.reduce((acc, url) => acc + (generated(url) ? 0.25 : 1.5), 0);
    return imageScore + candidateScore;
  };

  for (const person of merged) {
    // All merged persons come from verified/MBTI/wiki sources with non-empty names.
    const key = normalizeName(person.name);
    const next = withAvatarFallback(person);
    const current = unique.get(key);
    if (!current || score(next) > score(current)) {
      unique.set(key, next);
    }
  }

  // Only add the raw typed query as a fallback if it doesn't overlap with
  // any existing result (exact key match OR substring in either direction).
  const qKey = normalizeName(q);
  const alreadyCovered = Array.from(unique.keys()).some(
    (k) => k === qKey || k.includes(qKey) || qKey.includes(k)
  );
  if (!alreadyCovered) {
    unique.set(qKey, withAvatarFallback({ name: q, isCustom: true }));
  }

  return Array.from(unique.values())
    .sort((a, b) => {
      const aN = normalizeName(a.name);
      const bN = normalizeName(b.name);
      const aStarts = aN.startsWith(normalized) || aN.split(/\s+/).some((w) => w.startsWith(normalized)) ? 0 : 1;
      const bStarts = bN.startsWith(normalized) || bN.split(/\s+/).some((w) => w.startsWith(normalized)) ? 0 : 1;
      return aStarts - bStarts;
    })
    .slice(0, Math.max(1, limit));
}
